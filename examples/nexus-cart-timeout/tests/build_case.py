#!/usr/bin/env python3
"""Produce declarative LabWired UART RX and operator stimuli (no engine hacks)."""
import sys
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
TICK = 8000  # 8 MHz CPU -> cycles/ms
def inject(time_ms, seq, distance=1000):
    if seq == 'bad':
        # Invalid control byte followed by an otherwise valid frame.
        # Parser must reject the WHOLE line, not accept its valid suffix.
        frame = chr(1) + 'S,7,1000' + chr(10)
        payload = json.dumps([ord(c) for c in frame])
    else:
        frame = f'S,{seq},{distance}' + chr(10)
        payload = json.dumps(frame)
    return (f'  - uart: "uart1"\n'
            f'    bytes: {payload}\n'
            f'    trigger: !after_cycles {{ cycles: {time_ms*TICK} }}\n')
def button(time_ms, pressed, component):
    return (f'  - target: {{ component: "{component}", channel: "pressed" }}\n'
            f'    value: {int(pressed)}\n'
            f'    trigger: !after_cycles {{ cycles: {time_ms*TICK} }}\n')
def build(name):
    rows = [(0, 1), (20, 2), (40, 3), (60, 4), (80, 5), (100, 6)]
    if name in ('stale', 'recovery'):
        rows += [(t, 6) for t in (120,140,160,180,200)]
        rows += [(220,7),(240,8),(260,9),(280,10)]
        if name == 'recovery':
            rows += [(340,1),(360,2),(380,3),(400,4),(420,5),(440,6)]
    elif name == 'malformed':
        rows += [(120,'bad'),(140,6),(160,6),(180,6),(200,6)]
        rows += [(220,7),(240,8),(260,9),(280,10)]
    elif name == 'healthy':
        rows += [(t, 6 + (t-100)//20) for t in range(120,301,20)]
    elif name == 'no-start':
        rows += [(t, 6+(t-100)//20) for t in range(120,301,20)]
    elif name == 'missing':
        rows += [(220,7),(240,8),(260,9),(280,10)]  # completely missing 120..200
    else:
        raise ValueError(f'unknown case: {name}')
    script = f"""# Generated by build_case.py; do not edit; input stream is real USART1 RX.
schema_version: "1.2"
inputs:
  firmware: "../build/cart.elf"
  system: "../system.yaml"
limits:
  max_steps: 30000000
  max_cycles: {3840000 if name == 'recovery' else 2440000}
  wall_time_ms: 120000
uart_injections:
"""
    script += ''.join(inject(t, seq) for t, seq in rows)
    script += 'stimuli:\n'
    if name != 'no-start':
        script += button(50, True, 'operator_start')
        script += button(55, False, 'operator_start')
    if name == 'recovery':
        script += button(320, True, 'operator_reset')
        script += button(325, False, 'operator_reset')
        script += button(400, True, 'operator_start')
        script += button(405, False, 'operator_start')
    script += 'assertions:\n'
    script += '  - uart_contains: "BOOT_LOW"\n  - uart_contains: "FRESH seq=6"\n'
    if name != 'no-start':
        script += '  - uart_contains: "RUNNING"\n'
    if name in ('stale', 'missing', 'recovery', 'malformed'):
        script += ('  - uart_contains: "FAULT_LATCHED"\n'
                   '  - gpio_edges: { pin: "gpiob:0", min_edges: ' + ('3' if name == 'recovery' else '2') + ' }\n'
                   '  - memory_value: { address: 0x40010C0C, expected_value: ' + ('1' if name == 'recovery' else '0') + ', mask: 1, size: 4 }\n')
    else:
        script += '  - memory_value: { address: 0x40010C0C, expected_value: ' + ('0' if name=='no-start' else '1') + ', mask: 1, size: 4 }\n'
    script += '  - expected_stop_reason: max_cycles\n'
    path = HERE/f'{name}.yaml'
    path.write_text(script)
    print(path)
if __name__ == '__main__':
    for name in (sys.argv[1:] or ('stale','healthy','no-start','missing','recovery','malformed')):
        build(name)
