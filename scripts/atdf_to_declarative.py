#!/usr/bin/env python3
"""Generate a LabWired declarative register bank from a Microchip ATDF module.

ATDF is the device description Microchip ships in its AVR device family packs
(DFP). This turns one module's register group into the YAML the `declarative`
peripheral type loads: offsets, byte sizes, access and reset values, plus the
bit fields. It is a register bank only; behaviour belongs in a real model.

Usage:
    scripts/atdf_to_declarative.py ATmega4809.atdf CLKCTRL out.yaml \
        [--reset MCLKSTATUS=0x10] [--source "Microchip ATmega_DFP ..."]

`--reset NAME=VALUE` overrides a register's reset value where the ATDF has
none (factory-programmed rows such as SIGROW.DEVICEID) or where the data sheet
gives the run-time value of a status register. Every override is written into
the YAML header so it stays visible.
"""

import argparse
import sys
import xml.etree.ElementTree as ET

ACCESS = {"RW": "READ_WRITE", "R": "READ_ONLY", "W": "WRITE_ONLY"}


def parse_int(text, default=0):
    if text is None:
        return default
    return int(text, 0)


def bit_range(mask):
    low = (mask & -mask).bit_length() - 1
    high = mask.bit_length() - 1
    return low, high


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("atdf")
    ap.add_argument("module")
    ap.add_argument("out")
    ap.add_argument("--reset", action="append", default=[])
    ap.add_argument("--source", default="")
    args = ap.parse_args(argv)

    overrides = {}
    for item in args.reset:
        name, value = item.split("=", 1)
        overrides[name] = int(value, 0)

    root = ET.parse(args.atdf).getroot()
    # `<devices>` also lists each module (instances and offsets, no
    # registers); the register layout lives under `<modules>`.
    module = next(
        (
            m
            for m in root.iter("module")
            if m.get("name") == args.module and m.find("register-group/register") is not None
        ),
        None,
    )
    if module is None:
        sys.exit(f"module {args.module} not in {args.atdf}")
    group = next(module.iter("register-group"))

    lines = [
        f"# Generated by scripts/atdf_to_declarative.py from {args.source or args.atdf},",
        f"# module {args.module}. Register bank only: offsets, sizes, access and reset",
        "# values; no behaviour.",
    ]
    for name, value in sorted(overrides.items()):
        lines.append(f"# Reset override: {name} = {value:#04x} (not an ATDF initval).")
    lines += [f"peripheral: {args.module}", "version: 0.1.0", "registers:"]

    regs = sorted(group.iter("register"), key=lambda r: parse_int(r.get("offset")))
    for reg in regs:
        name = reg.get("name")
        size = parse_int(reg.get("size"), 1) * 8
        reset = overrides.get(name, parse_int(reg.get("initval")))
        lines += [
            f"- id: {name}",
            f"  address_offset: {parse_int(reg.get('offset'))}",
            f"  size: {size}",
            f"  access: {ACCESS.get(reg.get('rw', 'RW'), 'READ_WRITE')}",
            f"  reset_value: {reset}",
        ]
        fields = list(reg.iter("bitfield"))
        if fields:
            lines.append("  fields:")
            for field in fields:
                low, high = bit_range(parse_int(field.get("mask")))
                caption = (field.get("caption") or "").replace('"', "'")
                lines += [
                    f"  - name: {field.get('name')}",
                    f"    bit_range: [{high}, {low}]",
                    f'    description: "{caption}"',
                ]
        lines.append("  side_effects: null")

    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1:])
