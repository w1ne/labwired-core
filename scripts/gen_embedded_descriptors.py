#!/usr/bin/env python3
"""Regenerate crates/core/src/bus/embedded_descriptors.rs.

Embeds the configs/peripherals descriptors a chip YAML actually REFERENCES, so
SystemBus::from_config resolves them without a filesystem (wasm32 has no
std::fs). A descriptor missing here fails ONLY in the browser, at runtime, on
the lab that needs it — which is why this file must never be maintained by
hand: rp2040/esp32s3/nrf52832 were all silently absent while their chip YAMLs
referenced them. The embedded_descriptor_registry_is_complete test (native, has
fs) fails the build when this file goes stale.

REFERENCED, not "every file on disk". These YAMLs are `include_str!`d into every
binary, wasm included, and configs/peripherals holds far more than any chip
loads: an SVD import emits a descriptor per vendor peripheral, while a chip YAML
wires only the blocks it models. Embedding the whole tree put megabytes of YAML
that nothing can ever look up into the browser download. Native builds still
fall back to from_file, so an unreferenced descriptor stays usable on the CLI;
it just does not ride along in the wasm.

Two keys count as a reference, and they are not interchangeable:
  config.path         -- a `type: declarative` peripheral's real MODEL
  config.debug_schema -- decode metadata only, for a native peripheral

Usage: python3 scripts/gen_embedded_descriptors.py   (from the repo root)
"""

import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PERIPHERALS = ROOT / "configs" / "peripherals"
OUT = ROOT / "crates" / "core" / "src" / "bus" / "embedded_descriptors.rs"

