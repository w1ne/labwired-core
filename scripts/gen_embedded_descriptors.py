CHIPS = ROOT / "configs" / "chips"
# `config.path` loads a declarative peripheral's real model; `config.debug_schema`
# supplies decode metadata for a native one. Both make a descriptor reachable at
# runtime, so both must be embedded.
REF_KEY = re.compile(r"(?:path|debug_schema):\s*\"?([^\"\s]+\.yaml)\"?")


def referenced_keys() -> set[str]:
    """Descriptor keys some chip YAML can actually ask for at runtime."""
    keys = set()
    for chip in sorted(CHIPS.glob("*.yaml")):
        for value in REF_KEY.findall(chip.read_text()):
            if "peripherals/" in value:
                keys.add(value.rsplit("peripherals/", 1)[1])
    return keys


def main() -> None:
    on_disk = {p.relative_to(PERIPHERALS).as_posix() for p in PERIPHERALS.rglob("*.yaml")}
    wanted = referenced_keys()
    # A reference with no file is the failure this script exists to prevent, and
    # it must not be papered over: include_str! on a missing path fails the build
    # loudly, which is the right outcome, but say which chip is broken first.
    missing = sorted(wanted - on_disk)
    if missing:
        raise SystemExit(
            "chip YAML references descriptors that do not exist: " + ", ".join(missing)
        )
    keys = sorted(wanted)
    entries = [
        f'    ("{key}", include_str!(\n'
        f'        "../../../../configs/peripherals/{key}"\n'
        f"    )),"
        for key in keys
    ]
    OUT.write_text(HEADER + "\n".join(entries) + "\n" + FOOTER)
    # rustfmt owns the final shape (line collapsing etc.) so the emitted file
    # is byte-stable under `cargo fmt --check` regardless of fmt config.
    subprocess.run(["rustfmt", "--edition", "2021", str(OUT)], check=True)
    embedded = sum((PERIPHERALS / k).stat().st_size for k in keys)
    total = sum((PERIPHERALS / k).stat().st_size for k in on_disk)
    print(
        f"embedded {len(keys)}/{len(on_disk)} descriptors "
        f"({embedded / 1e6:.2f} MB of {total / 1e6:.2f} MB on disk) "
        f"into {OUT.relative_to(ROOT)}"
    )


if __name__ == "__main__":
    main()
