#!/usr/bin/env python3
"""Generate a LabWired declarative register file from an ESP-IDF `*_reg.h`.

ESP-IDF's per-SoC register headers (components/soc/<chip>/include/soc/*_reg.h)
describe every register as

    #define EXTMEM_PRO_ICACHE_CTRL1_REG (DR_REG_EXTMEM_BASE + 0x044)
    /* EXTMEM_PRO_ICACHE_MASK_BUS2 : R/W ;bitpos:[2] ;default: 1'b1 ; */

so the reset value and access of each register follow from its field comments.
This script turns that into the `registers:` list the declarative engine reads.
Only the registers named on the command line (or all, with no filter) are
emitted. A register whose fields are all RO is emitted RO, else R/W.

Usage:
  esp_idf_reg_header_to_yaml.py <reg.h> <BASE_MACRO> <peripheral name> \
      [--only REG,REG...] [--max-offset N] > out.yaml
"""
import argparse
import re
import sys
from pathlib import Path

REG_RE = re.compile(r"#define\s+(\w+)_REG\s+\(\s*(\w+)\s*\+\s*(0x[0-9a-fA-F]+)\s*\)")
FIELD_RE = re.compile(
    r"/\*\s*(\w+)\s*:\s*([A-Za-z/]+)\s*;\s*bitpos:\s*\[(\d+)(?::(\d+))?\]\s*;\s*"
    r"default:\s*(\d+)'([bdhx])([0-9a-fA-FxX_]+)\s*;"
)


def parse(text: str, base_macro: str):
    regs = []
    cur = None
    for line in text.splitlines():
        m = REG_RE.search(line)
        if m:
            name, base, off = m.group(1), m.group(2), int(m.group(3), 16)
            cur = None
            if base == base_macro:
                cur = {"id": name, "offset": off, "fields": []}
                regs.append(cur)
            continue
        f = FIELD_RE.search(line)
        if f and cur is not None:
            fname, access, hi, lo, _w, radix, val = f.groups()
            hi = int(hi)
            lo = int(lo) if lo is not None else hi
            if lo > hi:
                hi, lo = lo, hi
            base_n = {"b": 2, "d": 10, "h": 16, "x": 16}[radix]
            v = int(val.replace("_", ""), base_n)
            cur["fields"].append((fname, access.upper(), hi, lo, v))
    return regs


def reset_value(fields) -> int:
    rv = 0
    for _n, _a, hi, lo, v in fields:
        width = hi - lo + 1
        rv |= (v & ((1 << width) - 1)) << lo
    return rv & 0xFFFF_FFFF


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("header", type=Path)
    ap.add_argument("base_macro")
    ap.add_argument("peripheral")
    ap.add_argument("--only", default="")
    ap.add_argument("--max-offset", type=lambda s: int(s, 0), default=None)
    ap.add_argument("--source", default="")
    ap.add_argument(
        "--done",
        action="append",
        default=[],
        help="REG=MASK: completion-status bits. They reset set (the idle state a"
        " running chip is in after the boot ROM) and are set again one cycle"
        " after any write to REG, so an operation the firmware starts there"
        " completes at once. Repeatable.",
    )
    ap.add_argument(
        "--reset",
        action="append",
        default=[],
        help="REG=VALUE: replace the header's reset value with the state a"
        " running chip reads (e.g. an FSM-idle status register). Repeatable.",
    )
    args = ap.parse_args()
    regs = parse(args.header.read_text(), args.base_macro)
    only = {s.strip() for s in args.only.split(",") if s.strip()}
    done = {}
    for d in args.done:
        reg, mask = d.split("=")
        done[reg] = int(mask, 0)
    override = {}
    for d in args.reset:
        reg, value = d.split("=")
        override[reg] = int(value, 0)
    seen = set()
    out = [
        f"# {args.peripheral}: generated by scripts/esp_idf_reg_header_to_yaml.py",
        f"# from {args.source or args.header.name}. Reset values and access are the",
        "# header's own per-field `default:` / access annotations, except where the",
        "# generator command (below) names a running-state reset or done bits.",
        "# Command: " + " ".join(Path(a).name if a.endswith(".h") else a for a in sys.argv[1:]),
        f'peripheral: "{args.peripheral}"',
        'version: "0.1.0"',
        "registers:",
    ]
    for r in regs:
        if only and r["id"] not in only:
            continue
        if args.max_offset is not None and r["offset"] > args.max_offset:
            continue
        if r["offset"] in seen:
            continue
        seen.add(r["offset"])
        accesses = {a for (_n, a, _h, _l, _v) in r["fields"]}
        access = "RO" if accesses and accesses <= {"RO"} else "R/W"
        out.append(f'  - id: "{r["id"]}"')
        out.append(f"    address_offset: {r['offset']:#05x}")
        out.append("    size: 32")
        out.append(f'    access: "{access}"')
        rv = override.get(r["id"], reset_value(r["fields"])) | done.get(r["id"], 0)
        out.append(f"    reset_value: {rv:#010x}")
    if done:
        out.append("timing:")
        for reg, mask in done.items():
            out.append(f'  - id: "{reg.lower()}_done"')
            out.append(f'    trigger: !write {{ register: "{reg}" }}')
            out.append("    delay_cycles: 1")
            out.append(f'    action: {{ set_bits: {{ register: "{reg}", bits: {mask:#010x} }} }}')
    print("\n".join(out))
    missing = only - {r["id"] for r in regs}
    if missing:
        print(f"warning: not found: {sorted(missing)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
